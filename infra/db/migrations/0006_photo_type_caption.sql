-- 0006_photo_type_caption: what a field photo shows, a caption, and exact
-- file-key checks (Photo API, step 2).
--
-- Additive for data: camera_photos is empty when this runs on production (no
-- photo API deployed before it), and every existing row would get
-- photo_type 'other' and no caption. camera_points and all other tables are
-- untouched. Applied by scripts/db.sh in one transaction.

ALTER TABLE camera_photos
  ADD COLUMN photo_type text NOT NULL DEFAULT 'other' CHECK (photo_type IN (
    'site', 'installation_point', 'pole_structure', 'cabinet_equipment',
    'cable_route', 'other')),
  ADD COLUMN caption text CHECK (char_length(caption) <= 500);

-- Keys are generated by the API only (PhotoStorage.newKeys); accept exactly
-- that shape, so no stored key can ever contain "..", "./" or an absolute path.
ALTER TABLE camera_photos
  DROP CONSTRAINT camera_photos_file_key_check,
  DROP CONSTRAINT camera_photos_thumb_key_check,
  ADD CONSTRAINT camera_photos_file_key_check
    CHECK (file_key ~ '^photos/[0-9]{4}/[0-9]{2}/[0-9a-f-]{36}\.jpg$'),
  ADD CONSTRAINT camera_photos_thumb_key_check
    CHECK (thumb_key ~ '^photos/[0-9]{4}/[0-9]{2}/[0-9a-f-]{36}_t\.jpg$');

-- PATCH may change only these two columns; files and sizes stay as uploaded.
GRANT UPDATE (photo_type, caption) ON camera_photos TO cctv_app;
